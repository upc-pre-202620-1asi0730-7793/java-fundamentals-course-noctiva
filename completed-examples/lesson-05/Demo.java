// contenido en Main.java y cambia "class Demo" por "class Main".
class Demo {
    public static void main(String[] args) {
        for (int i = 1; i <= 5; i++) {
            System.out.println("Estudiante " + i);
        }

        int contador = 1;
        while (contador <= 5) {
            System.out.println("Registro " + contador);
            contador++;
        }
    }
}