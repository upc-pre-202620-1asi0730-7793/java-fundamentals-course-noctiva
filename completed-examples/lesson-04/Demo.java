// Lección 4: Código de la demostración (if-else).
// Para ejecutar en un editor online que requiere Main,
// copia este código en Main.java y cambia Demo por Main.
class Demo {
    public static void main(String[] args) {
        int nota = 16;

        if (nota >= 13) {
            System.out.println("Aprobado");
        } else {
            System.out.println("Desaprobado");
        }
    }
}
